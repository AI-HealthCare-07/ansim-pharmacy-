    mark_code_back_img = fields.TextField(null=True, description="마크뒤이미지")
    change_date = fields.CharField(max_length=50, null=True, description="변경일자")

    # 4. DUR품목정보
    bar_code = fields.CharField(max_length=100, null=True, description="바코드")
    material_name = fields.TextField(null=True, description="원료성분")
    ee_doc_id = fields.TextField(null=True, description="효능문서ID/내용")
    ud_doc_id = fields.TextField(null=True, description="용법문서ID/내용")
