    etc_otc_name = fields.CharField(max_length=100, null=True, description="전문/일반")
    form_code_name = fields.CharField(max_length=100, null=True, description="제형")
    mark_code_front_anal = fields.CharField(max_length=255, null=True, description="마크앞분석")
    mark_code_back_anal = fields.CharField(max_length=255, null=True, description="마크뒤분석")
