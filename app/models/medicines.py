    line_front = fields.CharField(max_length=100, null=True, description="분할선앞")
    line_back = fields.CharField(max_length=100, null=True, description="분할선뒤")
    leng_long = fields.CharField(max_length=50, null=True, description="크기(장축)")
    leng_short = fields.CharField(max_length=50, null=True, description="크기(단축)")
