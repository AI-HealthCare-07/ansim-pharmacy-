    bizrno = fields.CharField(max_length=50, null=True, description="사업자등록번호")

    # 2. e약은요
    efcy_qesitm = fields.TextField(null=True, description="효능효과")
    use_method_qesitm = fields.TextField(null=True, description="용법용량")
    atpn_warn_qesitm = fields.TextField(null=True, description="사용상주의사항 경고")
    atpn_qesitm = fields.TextField(null=True, description="사용상주의사항")
    intrc_qesitm = fields.TextField(null=True, description="상호작용")
    se_qesitm = fields.TextField(null=True, description="부작용")
    deposit_method_qesitm = fields.TextField(null=True, description="보관법")
